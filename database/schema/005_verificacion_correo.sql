-- BIIN: registros de viajeros que esperan confirmar su correo (RF01, RNF04, CU-01)
-- La cuenta en usuarios se crea solo cuando el viajero escribe el código que le llegó.
-- Si el correo no existe, el código nunca llega y la fila caduca sin crear la cuenta.
-- Los administradores, operadores y colaboradores se crean por script o desde administración
-- y no pasan por aquí.
-- Es idempotente: se puede ejecutar sobre una base que ya la tenga (database/actualizar_bd.ps1).

CREATE TABLE IF NOT EXISTS registros_pendientes (
    id_registro      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(120) NOT NULL,
    correo           varchar(254) NOT NULL,
    hash_contrasena  varchar(255) NOT NULL,
    hash_codigo      varchar(255) NOT NULL,
    intentos         smallint     NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    enviado_en       timestamptz  NOT NULL DEFAULT now(),
    expira_en        timestamptz  NOT NULL,
    CONSTRAINT ck_registros_pendientes_vigencia CHECK (expira_en > enviado_en)
);

-- Un solo registro pendiente por correo, sin importar mayúsculas (igual que usuarios)
CREATE UNIQUE INDEX IF NOT EXISTS ux_registros_pendientes_correo ON registros_pendientes (lower(correo));
CREATE INDEX IF NOT EXISTS ix_registros_pendientes_expira ON registros_pendientes (expira_en);
