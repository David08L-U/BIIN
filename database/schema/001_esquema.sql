-- BIIN: esquema principal de PostgreSQL (27 tablas del modelo en 3FN)
-- Ejecutar sobre una base vacía, en orden: schema, triggers, seed.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Usuarios y ubicación geográfica

CREATE TABLE usuarios (
    id_usuario       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(120) NOT NULL,
    correo           varchar(254) NOT NULL,
    hash_contrasena  varchar(255) NOT NULL,
    activo           boolean      NOT NULL DEFAULT true,
    fecha_registro   timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_usuarios_correo ON usuarios (lower(correo));

CREATE TABLE roles (
    id_rol  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  varchar(40) NOT NULL UNIQUE
);

CREATE TABLE usuario_rol (
    id_usuario  integer NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    id_rol      integer NOT NULL REFERENCES roles (id_rol) ON DELETE RESTRICT,
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE municipios (
    id_municipio  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        varchar(10)  NOT NULL UNIQUE,
    nombre        varchar(100) NOT NULL UNIQUE
);

CREATE TABLE localidades (
    id_localidad  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_municipio  integer      NOT NULL REFERENCES municipios (id_municipio) ON DELETE RESTRICT,
    nombre        varchar(120) NOT NULL,
    UNIQUE (id_municipio, nombre)
);

CREATE TABLE ubicaciones (
    id_ubicacion          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_localidad          integer       NOT NULL REFERENCES localidades (id_localidad) ON DELETE RESTRICT,
    direccion_referencia  varchar(255),
    latitud               numeric(9, 6) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud              numeric(9, 6) NOT NULL CHECK (longitud BETWEEN -180 AND 180)
);
CREATE INDEX ix_ubicaciones_localidad ON ubicaciones (id_localidad);

-- Contenidos de la plataforma

CREATE TABLE recursos (
    id_recurso          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                varchar(10)  NOT NULL CHECK (tipo IN ('ruta', 'negocio', 'evento', 'lugar')),
    titulo              varchar(150) NOT NULL,
    descripcion         text,
    estado_publicacion  varchar(10)  NOT NULL DEFAULT 'pendiente'
                        CHECK (estado_publicacion IN ('pendiente', 'publicado', 'archivado')),
    id_creador          integer      NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    id_revisor          integer      REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    fecha_revision      timestamptz,
    actualizado_en      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_recursos_tipo_estado ON recursos (tipo, estado_publicacion);

CREATE TABLE categorias (
    id_categoria  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        varchar(60) NOT NULL UNIQUE
);

CREATE TABLE recurso_categoria (
    id_recurso    integer NOT NULL REFERENCES recursos (id_recurso) ON DELETE CASCADE,
    id_categoria  integer NOT NULL REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
    PRIMARY KEY (id_recurso, id_categoria)
);

CREATE TABLE fotografias (
    id_fotografia      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recurso         integer      NOT NULL REFERENCES recursos (id_recurso) ON DELETE CASCADE,
    url_archivo        varchar(500) NOT NULL,
    texto_alternativo  varchar(255) NOT NULL,
    orden              integer      NOT NULL CHECK (orden > 0),
    UNIQUE (id_recurso, orden)
);

CREATE TABLE colaborador_recurso (
    id_usuario  integer NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    id_recurso  integer NOT NULL REFERENCES recursos (id_recurso) ON DELETE CASCADE,
    PRIMARY KEY (id_usuario, id_recurso)
);

CREATE TABLE negocios (
    id_recurso           integer PRIMARY KEY REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    id_ubicacion         integer NOT NULL REFERENCES ubicaciones (id_ubicacion) ON DELETE RESTRICT,
    telefono             varchar(20),
    precio_minimo_aprox  numeric(10, 2) CHECK (precio_minimo_aprox >= 0),
    precio_maximo_aprox  numeric(10, 2) CHECK (precio_maximo_aprox >= 0),
    CHECK (precio_maximo_aprox IS NULL OR precio_minimo_aprox IS NULL
           OR precio_maximo_aprox >= precio_minimo_aprox)
);

CREATE TABLE eventos (
    id_recurso            integer PRIMARY KEY REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    id_ubicacion          integer     NOT NULL REFERENCES ubicaciones (id_ubicacion) ON DELETE RESTRICT,
    inicio                timestamptz NOT NULL,
    fin                   timestamptz NOT NULL,
    costo_entrada         numeric(10, 2) CHECK (costo_entrada >= 0),
    estado_evento         varchar(12) NOT NULL DEFAULT 'programado'
                          CHECK (estado_evento IN ('programado', 'cancelado', 'finalizado')),
    contacto_organizador  varchar(150),
    CHECK (fin >= inicio)
);
CREATE INDEX ix_eventos_inicio ON eventos (inicio);

CREATE TABLE lugares (
    id_recurso          integer PRIMARY KEY REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    id_ubicacion        integer NOT NULL REFERENCES ubicaciones (id_ubicacion) ON DELETE RESTRICT,
    costo_acceso        numeric(10, 2) CHECK (costo_acceso >= 0),
    condiciones_acceso  text
);

CREATE TABLE horarios_visita (
    id_horario     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recurso     integer  NOT NULL REFERENCES recursos (id_recurso) ON DELETE CASCADE,
    dia_semana     smallint NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    hora_apertura  time     NOT NULL,
    hora_cierre    time     NOT NULL
);
CREATE INDEX ix_horarios_visita_recurso ON horarios_visita (id_recurso);

-- Transporte intermunicipal

CREATE TABLE rutas (
    id_recurso  integer PRIMARY KEY REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    codigo      varchar(20) NOT NULL UNIQUE,
    activa      boolean     NOT NULL DEFAULT true
);

CREATE TABLE ruta_parada (
    id_ruta            integer NOT NULL REFERENCES rutas (id_recurso) ON DELETE RESTRICT,
    orden              integer NOT NULL CHECK (orden > 0),
    id_ubicacion       integer NOT NULL REFERENCES ubicaciones (id_ubicacion) ON DELETE RESTRICT,
    permite_abordar    boolean NOT NULL DEFAULT true,
    permite_descender  boolean NOT NULL DEFAULT true,
    PRIMARY KEY (id_ruta, orden)
);
CREATE INDEX ix_ruta_parada_ubicacion ON ruta_parada (id_ubicacion);

CREATE TABLE puntos_recorrido (
    id_ruta   integer       NOT NULL REFERENCES rutas (id_recurso) ON DELETE CASCADE,
    orden     integer       NOT NULL CHECK (orden > 0),
    latitud   numeric(9, 6) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud  numeric(9, 6) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    PRIMARY KEY (id_ruta, orden)
);

CREATE TABLE horarios_ruta (
    id_horario     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ruta        integer  NOT NULL REFERENCES rutas (id_recurso) ON DELETE RESTRICT,
    dia_semana     smallint NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    hora_salida    time     NOT NULL,
    vigente_desde  date     NOT NULL,
    vigente_hasta  date,
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);
CREATE INDEX ix_horarios_ruta_ruta ON horarios_ruta (id_ruta, dia_semana);

CREATE TABLE tarifas (
    id_tarifa      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ruta        integer        NOT NULL,
    orden_origen   integer        NOT NULL,
    orden_destino  integer        NOT NULL,
    monto          numeric(10, 2) NOT NULL CHECK (monto >= 0),
    vigente_desde  date           NOT NULL,
    vigente_hasta  date,
    FOREIGN KEY (id_ruta, orden_origen)  REFERENCES ruta_parada (id_ruta, orden) ON DELETE RESTRICT,
    FOREIGN KEY (id_ruta, orden_destino) REFERENCES ruta_parada (id_ruta, orden) ON DELETE RESTRICT,
    CHECK (orden_destino > orden_origen),
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
    -- No puede haber dos tarifas vigentes al mismo tiempo para el mismo tramo
    EXCLUDE USING gist (
        id_ruta WITH =,
        orden_origen WITH =,
        orden_destino WITH =,
        daterange(vigente_desde, vigente_hasta, '[]') WITH &&
    )
);

CREATE TABLE unidades (
    id_unidad      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador  varchar(30) NOT NULL UNIQUE,
    capacidad      integer     NOT NULL CHECK (capacidad > 0),
    activa         boolean     NOT NULL DEFAULT true
);

CREATE TABLE salidas (
    id_salida             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ruta               integer     NOT NULL REFERENCES rutas (id_recurso) ON DELETE RESTRICT,
    id_unidad             integer     NOT NULL REFERENCES unidades (id_unidad) ON DELETE RESTRICT,
    salida_programada     timestamptz NOT NULL,
    capacidad_habilitada  integer     NOT NULL CHECK (capacidad_habilitada > 0),
    estado                varchar(12) NOT NULL DEFAULT 'programada'
                          CHECK (estado IN ('programada', 'en_curso', 'finalizada', 'cancelada'))
);
CREATE INDEX ix_salidas_ruta_fecha ON salidas (id_ruta, salida_programada);

CREATE TABLE operador_ruta (
    id_usuario  integer NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    id_ruta     integer NOT NULL REFERENCES rutas (id_recurso) ON DELETE CASCADE,
    PRIMARY KEY (id_usuario, id_ruta)
);

CREATE TABLE reportes_cupo (
    id_reporte            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_salida             integer     NOT NULL REFERENCES salidas (id_salida) ON DELETE RESTRICT,
    id_autor              integer     NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    asientos_disponibles  integer     NOT NULL CHECK (asientos_disponibles >= 0),
    registrado_en         timestamptz NOT NULL DEFAULT now(),
    valido_hasta          timestamptz NOT NULL,
    CHECK (valido_hasta > registrado_en)
);
CREATE INDEX ix_reportes_cupo_salida ON reportes_cupo (id_salida, valido_hasta DESC);

-- Planificación de viaje

CREATE TABLE itinerarios (
    id_itinerario         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            integer      NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    nombre                varchar(120) NOT NULL,
    inicio                date         NOT NULL,
    fin                   date         NOT NULL,
    presupuesto_estimado  numeric(10, 2) CHECK (presupuesto_estimado >= 0),
    fecha_creacion        timestamptz  NOT NULL DEFAULT now(),
    CHECK (fin >= inicio)
);
CREATE INDEX ix_itinerarios_usuario ON itinerarios (id_usuario);

CREATE TABLE actividades_itinerario (
    id_actividad     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_itinerario    integer     NOT NULL REFERENCES itinerarios (id_itinerario) ON DELETE CASCADE,
    id_recurso       integer     NOT NULL REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    orden            integer     NOT NULL CHECK (orden > 0),
    inicio_previsto  timestamptz,
    fin_previsto     timestamptz,
    notas            text,
    UNIQUE (id_itinerario, orden),
    CHECK (fin_previsto IS NULL OR inicio_previsto IS NULL OR fin_previsto >= inicio_previsto)
);

CREATE TABLE favoritos (
    id_usuario      integer     NOT NULL REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    id_recurso      integer     NOT NULL REFERENCES recursos (id_recurso) ON DELETE CASCADE,
    fecha_guardado  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id_usuario, id_recurso)
);
