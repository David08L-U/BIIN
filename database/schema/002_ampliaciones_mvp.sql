-- BIIN: tablas agregadas para completar el MVP (fuera de las 27 originales)
-- Recorridos sugeridos cubre CU-13; bitácora cubre el paquete 17.1.5.

CREATE TABLE recorridos_sugeridos (
    id_recorrido        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo              varchar(150) NOT NULL,
    descripcion         text,
    id_localidad_base   integer      NOT NULL REFERENCES localidades (id_localidad) ON DELETE RESTRICT,
    estado_publicacion  varchar(10)  NOT NULL DEFAULT 'pendiente'
                        CHECK (estado_publicacion IN ('pendiente', 'publicado', 'archivado')),
    actualizado_en      timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE etapas_recorrido (
    id_recorrido            integer NOT NULL REFERENCES recorridos_sugeridos (id_recorrido) ON DELETE CASCADE,
    orden                   integer NOT NULL CHECK (orden > 0),
    id_recurso              integer NOT NULL REFERENCES recursos (id_recurso) ON DELETE RESTRICT,
    duracion_sugerida_min   integer CHECK (duracion_sugerida_min > 0),
    PRIMARY KEY (id_recorrido, orden)
);

CREATE TABLE bitacora_admin (
    id_bitacora  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   integer     NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    accion       varchar(10) NOT NULL CHECK (accion IN ('crear', 'editar', 'publicar', 'archivar', 'eliminar')),
    tabla        varchar(60) NOT NULL,
    id_registro  varchar(60) NOT NULL,
    detalle      jsonb,
    fecha        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_bitacora_fecha ON bitacora_admin (fecha DESC);
